import React, { useEffect, useState } from 'react';
import {
  Bar,
  BarChart,
  CartesianGrid,
  Cell,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from 'recharts';
import { Calculator, Info, Loader2 } from 'lucide-react';
import { api, formatINR, formatLPA } from '../../services/api';
import {
  CandidateProfile,
  ModelMetricsResponse,
  SalaryPredictionResult,
} from '../../types';

interface SalaryPredictionViewProps {
  profile: CandidateProfile;
  initialPrediction: SalaryPredictionResult;
}

export const SalaryPredictionView: React.FC<SalaryPredictionViewProps> = ({
  profile,
  initialPrediction,
}) => {
  const [metricsInfo, setMetricsInfo] = useState<ModelMetricsResponse | null>(null);
  const [prediction, setPrediction] = useState<SalaryPredictionResult>(initialPrediction);
  const [history, setHistory] = useState<SalaryPredictionResult[]>([]);

  // Interactive what-if inputs
  const [jobRole, setJobRole] = useState(profile.preferredRole);
  const [city, setCity] = useState(profile.city);
  const [educationLevel, setEducationLevel] = useState(profile.educationLevel);
  const [experienceYears, setExperienceYears] = useState(profile.experienceYears);
  const [employmentStatus, setEmploymentStatus] = useState(profile.employmentStatus);
  const [skillsText, setSkillsText] = useState(profile.skills.join(', '));

  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    api.getModelMetrics().then(setMetricsInfo).catch(() => {});
    api.getSalaryHistory().then((r) => setHistory(r.history)).catch(() => {});
  }, []);

  const handlePredict = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);
    setLoading(true);
    try {
      const skillsArray = skillsText
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean);
      const res = await api.predictSalary({
        jobRole,
        city,
        educationLevel,
        experienceYears: Number(experienceYears),
        employmentStatus,
        skills: skillsArray,
      });
      setPrediction(res);
      const h = await api.getSalaryHistory();
      setHistory(h.history);
    } catch (err) {
      setError((err as Error).message);
    } finally {
      setLoading(false);
    }
  };

  const roles = metricsInfo?.datasetStats.roles || [
    'Python Developer',
    'Data Scientist',
    'Full Stack Developer',
    'Frontend Developer',
    'Backend Developer',
    'Machine Learning Engineer',
    'Data Analyst',
    'Cloud / DevOps Engineer',
    'Java Developer',
    'Android Developer',
  ];
  const cities = metricsInfo?.datasetStats.cities || [
    'Bengaluru',
    'Hyderabad',
    'Pune',
    'Chennai',
    'Mumbai',
    'Delhi NCR',
    'Kochi',
    'Ahmedabad',
  ];
  const edus = metricsInfo?.datasetStats.educationLevels || [
    'B.Tech / B.E.',
    'M.Tech / M.E.',
    'MCA',
    'M.Sc',
    'BCA',
    'B.Sc',
  ];

  const factorChartData = prediction.factors.map((f) => ({
    name: f.factor.split('(')[0].trim(),
    impact: f.impactInr,
  }));

  return (
    <div className="space-y-6">
      <div>
        <h1 className="font-display text-2xl font-bold text-slate-900">
          AI Salary Prediction Engine
        </h1>
        <p className="text-sm text-slate-600 mt-1">
          Test compensation scenarios in INR (₹) using our trained regression model with TF-IDF
          skill features and categorical encoders.
        </p>
      </div>

      {/* Transparency Banner */}
      <div className="p-4 rounded-xl bg-blue-50/70 border border-blue-200 flex items-start gap-3 text-xs text-slate-700">
        <Info className="w-4 h-4 text-blue-700 shrink-0 mt-0.5" />
        <p className="leading-relaxed">
          <strong>Illustrative Demonstration Estimate:</strong>{' '}
          {metricsInfo?.datasetStats.disclaimer ||
            'Predictions are generated by a live ML model trained on a curated demonstration CSV dataset for the Indian tech market. Estimates are illustrative, not guaranteed offers.'}
        </p>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        {/* Estimator Form */}
        <form
          onSubmit={handlePredict}
          className="lg:col-span-5 bg-white border border-slate-200 rounded-xl p-6 space-y-4"
        >
          <h2 className="font-display text-base font-semibold text-slate-900">
            Prediction Parameters
          </h2>

          {error && (
            <div className="p-3 rounded-lg bg-red-50 border border-red-200 text-xs text-red-800">
              {error}
            </div>
          )}

          <div>
            <label className="block text-xs font-medium text-slate-700 mb-1">Target Job Role</label>
            <select
              value={jobRole}
              onChange={(e) => setJobRole(e.target.value)}
              className="w-full px-3 py-2 text-sm bg-white border border-slate-300 rounded-lg"
            >
              {roles.map((r) => (
                <option key={r} value={r}>
                  {r}
                </option>
              ))}
            </select>
          </div>

          <div className="grid grid-cols-2 gap-3">
            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">City</label>
              <select
                value={city}
                onChange={(e) => setCity(e.target.value)}
                className="w-full px-3 py-2 text-sm bg-white border border-slate-300 rounded-lg"
              >
                {cities.map((c) => (
                  <option key={c} value={c}>
                    {c}
                  </option>
                ))}
              </select>
            </div>
            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">
                Experience (Years)
              </label>
              <input
                type="number"
                min={0}
                max={25}
                step={0.5}
                value={experienceYears}
                onChange={(e) => setExperienceYears(Number(e.target.value))}
                className="w-full px-3 py-2 text-sm font-mono tabular-nums border border-slate-300 rounded-lg"
              />
            </div>
          </div>

          <div className="grid grid-cols-2 gap-3">
            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">Education</label>
              <select
                value={educationLevel}
                onChange={(e) => setEducationLevel(e.target.value)}
                className="w-full px-3 py-2 text-sm bg-white border border-slate-300 rounded-lg"
              >
                {edus.map((ed) => (
                  <option key={ed} value={ed}>
                    {ed}
                  </option>
                ))}
              </select>
            </div>
            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">Status</label>
              <select
                value={employmentStatus}
                onChange={(e) => setEmploymentStatus(e.target.value)}
                className="w-full px-3 py-2 text-sm bg-white border border-slate-300 rounded-lg"
              >
                <option value="Student / Final Year">Student / Final Year</option>
                <option value="Fresher / Job Seeker">Fresher / Job Seeker</option>
                <option value="Employed">Employed</option>
                <option value="Freelancer">Freelancer</option>
              </select>
            </div>
          </div>

          <div>
            <label className="block text-xs font-medium text-slate-700 mb-1">
              Technical Skills (comma-separated)
            </label>
            <textarea
              rows={3}
              value={skillsText}
              onChange={(e) => setSkillsText(e.target.value)}
              placeholder="Python, SQL, Django, REST API, Git, Docker"
              className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg focus:outline-none focus:ring-2 focus:ring-blue-600"
            />
          </div>

          <button
            type="submit"
            disabled={loading}
            className="w-full py-2.5 px-4 bg-blue-700 hover:bg-blue-800 disabled:opacity-60 text-white text-sm font-semibold rounded-lg flex items-center justify-center gap-2 cursor-pointer"
          >
            {loading ? <Loader2 className="w-4 h-4 animate-spin" /> : <Calculator className="w-4 h-4" />}
            Predict Annual Salary
          </button>
        </form>

        {/* Prediction Results & Factor Analysis */}
        <div className="lg:col-span-7 space-y-6">
          <div className="bg-slate-900 text-white rounded-xl p-6">
            <div className="flex flex-wrap items-center justify-between gap-2 text-xs text-slate-300">
              <span>Estimated Annual CTC (INR)</span>
              <span className="font-mono">Model: {prediction.modelUsed}</span>
            </div>
            <p className="mt-2 text-4xl font-bold font-mono tabular-nums tracking-tight">
              {formatINR(prediction.predictedSalary)}
            </p>
            <div className="mt-4 grid grid-cols-1 sm:grid-cols-3 gap-4 pt-4 border-t border-slate-700/80 text-sm">
              <div>
                <p className="text-xs text-slate-400">Estimated Range</p>
                <p className="font-mono tabular-nums font-semibold mt-0.5">
                  {formatINR(prediction.minSalary)} – {formatINR(prediction.maxSalary)}
                </p>
              </div>
              <div>
                <p className="text-xs text-slate-400">Monthly Equivalent</p>
                <p className="font-mono tabular-nums font-semibold mt-0.5 text-cyan-300">
                  {formatINR(prediction.monthlySalary)} / mo
                </p>
              </div>
              <div>
                <p className="text-xs text-slate-400">LPA Equivalent</p>
                <p className="font-mono tabular-nums font-semibold mt-0.5">
                  {formatLPA(prediction.predictedSalary)}
                </p>
              </div>
            </div>
          </div>

          {/* Factor Impact Chart + Explanations */}
          <div className="bg-white border border-slate-200 rounded-xl p-6">
            <h3 className="font-display text-base font-semibold text-slate-900 mb-1">
              Key Factors Affecting This Prediction
            </h3>
            <p className="text-xs text-slate-500 mb-4">
              Counterfactual feature attribution computed directly by the trained regressor
            </p>
            <div className="h-44 w-full mb-4">
              <ResponsiveContainer width="100%" height="100%">
                <BarChart data={factorChartData} margin={{ top: 5, right: 16, left: 10, bottom: 5 }}>
                  <CartesianGrid strokeDasharray="3 3" stroke="#E2E8F0" />
                  <XAxis dataKey="name" tick={{ fontSize: 12, fill: '#475569' }} />
                  <YAxis
                    tick={{ fontSize: 11, fill: '#475569' }}
                    tickFormatter={(v) => `₹${(Number(v) / 100000).toFixed(1)}L`}
                  />
                  <Tooltip
                    formatter={(val) => [formatINR(Number(val)), 'Estimated Impact']}
                    contentStyle={{ borderRadius: '8px', borderColor: '#E2E8F0', fontSize: '12px' }}
                  />
                  <Bar dataKey="impact" radius={[4, 4, 0, 0]} barSize={34}>
                    {factorChartData.map((entry, index) => (
                      <Cell
                        key={`cell-${index}`}
                        fill={entry.impact >= 0 ? '#1D4ED8' : '#DC2626'}
                      />
                    ))}
                  </Bar>
                </BarChart>
              </ResponsiveContainer>
            </div>

            <div className="divide-y divide-slate-200">
              {prediction.factors.map((f) => (
                <div key={f.factor} className="py-2.5 flex items-start justify-between gap-4 text-xs">
                  <div>
                    <p className="font-semibold text-slate-900">{f.factor}</p>
                    <p className="text-slate-600 mt-0.5">{f.detail}</p>
                  </div>
                  <span
                    className={`font-mono tabular-nums font-semibold whitespace-nowrap ${
                      f.impactInr > 0
                        ? 'text-emerald-700'
                        : f.impactInr < 0
                        ? 'text-red-700'
                        : 'text-slate-600'
                    }`}
                  >
                    {f.impactInr >= 0 ? `+${formatINR(f.impactInr)}` : formatINR(f.impactInr)}
                  </span>
                </div>
              ))}
            </div>
          </div>
        </div>
      </div>

      {/* Model Evaluation Benchmark Table */}
      {metricsInfo && (
        <div className="bg-white border border-slate-200 rounded-xl p-6">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 mb-4">
            <div>
              <h2 className="font-display text-base font-semibold text-slate-900">
                ML Model Evaluation Report (80/20 Train-Test Split)
              </h2>
              <p className="text-xs text-slate-500 mt-0.5">
                {metricsInfo.datasetStats.cleanedRows} cleaned rows ({metricsInfo.datasetStats.duplicatesRemoved} duplicates removed ·{' '}
                {metricsInfo.datasetStats.missingValuesImputed} missing values imputed ·{' '}
                {metricsInfo.datasetStats.featureCount} features)
              </p>
            </div>
            <span className="text-xs font-semibold text-blue-700">
              Selected Best: {metricsInfo.bestModelName}
            </span>
          </div>

          <div className="overflow-x-auto">
            <table className="w-full text-sm text-left">
              <thead>
                <tr className="border-b border-slate-200 text-xs font-semibold text-slate-500">
                  <th className="py-2.5 pr-4">Regression Model</th>
                  <th className="py-2.5 px-4 text-right">MAE (₹)</th>
                  <th className="py-2.5 px-4 text-right">RMSE (₹)</th>
                  <th className="py-2.5 px-4 text-right">MSE</th>
                  <th className="py-2.5 pl-4 text-right">R² Score</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-200">
                {metricsInfo.metrics.map((m) => (
                  <tr key={m.modelName} className={m.isBest ? 'bg-blue-50/50' : ''}>
                    <td className="py-3 pr-4 font-medium text-slate-900">
                      {m.modelName}
                      {m.isBest && (
                        <span className="ml-2 text-xs font-semibold text-blue-700">
                          (Active Model)
                        </span>
                      )}
                    </td>
                    <td className="py-3 px-4 text-right font-mono tabular-nums text-slate-700">
                      {formatINR(m.mae)}
                    </td>
                    <td className="py-3 px-4 text-right font-mono tabular-nums text-slate-700">
                      {formatINR(m.rmse)}
                    </td>
                    <td className="py-3 px-4 text-right font-mono tabular-nums text-slate-500">
                      {m.mse.toExponential(2)}
                    </td>
                    <td className="py-3 pl-4 text-right font-mono tabular-nums font-semibold text-slate-900">
                      {m.r2.toFixed(4)}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}

      {/* Prediction History */}
      {history.length > 0 && (
        <div className="bg-white border border-slate-200 rounded-xl p-6">
          <h2 className="font-display text-base font-semibold text-slate-900 mb-4">
            Recent Prediction History
          </h2>
          <div className="overflow-x-auto">
            <table className="w-full text-sm text-left">
              <thead>
                <tr className="border-b border-slate-200 text-xs font-semibold text-slate-500">
                  <th className="py-2 pr-4">Role &amp; City</th>
                  <th className="py-2 px-4">Model</th>
                  <th className="py-2 px-4 text-right">Predicted CTC</th>
                  <th className="py-2 pl-4 text-right">Monthly</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-200">
                {history.slice(0, 6).map((item, idx) => {
                  const snap = (item.inputSnapshot || {}) as Record<string, unknown>;
                  return (
                    <tr key={item.id || idx}>
                      <td className="py-2.5 pr-4 text-slate-800">
                        {String(snap.jobRole || profile.preferredRole)} ·{' '}
                        <span className="text-slate-500">{String(snap.city || profile.city)}</span>
                      </td>
                      <td className="py-2.5 px-4 text-xs text-slate-600">{item.modelUsed}</td>
                      <td className="py-2.5 px-4 text-right font-mono tabular-nums font-semibold text-slate-900">
                        {formatINR(item.predictedSalary)}
                      </td>
                      <td className="py-2.5 pl-4 text-right font-mono tabular-nums text-slate-600">
                        {formatINR(item.monthlySalary)}
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        </div>
      )}
    </div>
  );
};
